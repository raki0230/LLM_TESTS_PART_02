from typing import Optional
from dotenv import load_dotenv
from pydantic import BaseModel, Field
from langchain_core.prompts import ChatPromptTemplate
from langchain_openai import ChatOpenAI
from langsmith import traceable

load_dotenv()


class EvaluationResult(BaseModel):
    """Structured evaluation returned by the LLM judge."""

    correctness: int = Field(
        ge=1,
        le=10,
        description="How factually correct the response is."
    )

    relevance: int = Field(
        ge=1,
        le=10,
        description="How directly the response addresses the question."
    )

    clarity: int = Field(
        ge=1,
        le=10,
        description="How clear and understandable the response is."
    )

    completeness: int = Field(
        ge=1,
        le=10,
        description="How completely the response addresses the question."
    )

    overall: int = Field(
        ge=1,
        le=10,
        description="Overall quality of the response."
    )


class LLMAsJudge:
    """Evaluate an LLM response using another LLM as the judge."""

    def __init__(self):
        self.judge_llm = ChatOpenAI(
            model="gpt-4o-mini",
            temperature=0
        ).with_structured_output(EvaluationResult)

    @traceable(name="llm_as_judge")
    def judge_response(
        self,
        question: str,
        response: str,
        reference: Optional[str] = None
    ) -> EvaluationResult:

        evaluation_prompt = ChatPromptTemplate.from_template(
            """
You are an expert evaluator for an AI-powered banking assistant.

Evaluate the generated response against the user's question.

Question:
{question}

Generated Response:
{response}

{reference_section}

Evaluate the response using these criteria:

1. Correctness
   - Are the claims factually accurate?
   - Does the response avoid unsupported claims?

2. Relevance
   - Does the response directly answer the user's question?
   - Does it avoid unnecessary information?

3. Clarity
   - Is the response easy to understand?
   - Is it written in a clear and concise way?

4. Completeness
   - Does the response cover the important aspects of the question?
   - Are any important considerations missing?

5. Overall
   - Give an overall quality score considering all criteria.

Score each criterion from 1 to 10.
"""
        )

        reference_section = ""

        if reference:
            reference_section = f"""
Reference Answer:
{reference}
"""

        prompt = evaluation_prompt.format(
            question=question,
            response=response,
            reference_section=reference_section
        )

        return self.judge_llm.invoke(prompt)


def demo_llm_as_judge():

    judge = LLMAsJudge()

    question = """
    My credit card transaction was declined even though I have
    sufficient balance. What could be the reason?
    """

    # Output generated by the LLM under test
    llm_response = """
    A transaction can be declined for several reasons even when
    you have sufficient balance. The card may be blocked, the
    transaction may have triggered a fraud check, the merchant
    may not accept your card, or you may have exceeded a
    transaction limit.

    You should check whether your card is active and contact
    your bank if the issue continues.
    """

    # Expected/reference answer
    reference_answer = """
    A card transaction can be declined despite having sufficient
    balance because of reasons such as a blocked or expired card,
    incorrect card details, transaction limits, merchant
    restrictions, or fraud or security checks.

    The customer should verify the card status and transaction
    details and contact the bank if the problem persists.
    """

    print("LLM-AS-A-JUDGE")
    print("=" * 50)

    print("\nQuestion:")
    print(question.strip())

    print("\nGenerated Response:")
    print(llm_response.strip())

    evaluation = judge.judge_response(
        question=question,
        response=llm_response,
        reference=reference_answer
    )

    print("\nEvaluation:")
    print(f"Correctness   : {evaluation.correctness}/10")
    print(f"Relevance     : {evaluation.relevance}/10")
    print(f"Clarity       : {evaluation.clarity}/10")
    print(f"Completeness  : {evaluation.completeness}/10")
    print(f"Overall       : {evaluation.overall}/10")


if __name__ == "__main__":
    demo_llm_as_judge()